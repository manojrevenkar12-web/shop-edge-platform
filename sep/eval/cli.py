"""python -m sep.eval.cli {evaluate | heldout | gate | readme [--check] | quick | rules}"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import UTC, datetime

from sep.config import CONFIG, ROOT, load
from sep.eval.run import run_all, summarize

REPORTS = ROOT / "reports"
LOCK = CONFIG / "heldout.lock"
RULES = ROOT / "ops" / "prometheus" / "rules.yml"
K8S_RULES = ROOT / "deploy" / "k8s" / "base" / "slo-rules.yaml"


def _write(name: str, data: dict) -> None:
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / f"{name}.json").write_text(json.dumps(data, indent=1, sort_keys=True) + "\n")


def _config_hash() -> str:
    h = hashlib.sha256()
    for name in ("world", "heldout", "platform", "slo", "gate"):
        h.update((CONFIG / f"{name}.yaml").read_bytes())
    return h.hexdigest()[:16]


def gate(summary: dict) -> list[str]:
    g = load("gate")["platform"]
    p = summary["designs"]["platform"]
    fails = []
    if p["availability"] < g["min_availability"]:
        fails.append(f"availability {p['availability']:.4%}")
    if p["bf_availability"] is not None and p["bf_availability"] < g["min_black_friday_availability"]:
        fails.append(f"Black Friday availability {p['bf_availability']:.4%}")
    if p["wrong_per_100k"] > g["max_wrong_price_per_100k"]:
        fails.append(f"wrong prices {p['wrong_per_100k']} per 100k views")
    if p["reached_everyone"] > g["max_reached_everyone"]:
        fails.append(f"{p['reached_everyone']} broken builds reached everyone")
    if p["false_pages_per_week"] > g["max_false_pages_per_week"]:
        fails.append(f"{p['false_pages_per_week']} false pages a week")
    if p["episodes"] and p["detected"] / p["episodes"] < g["min_detected_share"]:
        fails.append(f"detected {p['detected']} of {p['episodes']} episodes")
    return fails


def rules() -> bool:
    """ops/prometheus/rules.yml for promtool, and the same groups as a Managed Prometheus `Rules` resource."""
    import yaml

    from sep.slo.burnrate import rules_yaml

    text = rules_yaml(load("slo"))
    cr = "# Generated by python -m sep.eval.cli rules from config/slo.yaml. Do not edit.\n" + yaml.safe_dump(
        {"apiVersion": "monitoring.googleapis.com/v1", "kind": "Rules", "metadata": {"name": "shop-slo"},
         "spec": yaml.safe_load(text)}, sort_keys=False, width=200)
    changed = False
    for path, body in ((RULES, text), (K8S_RULES, cr)):
        changed |= not path.exists() or path.read_text() != body
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    return changed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="sep.eval.cli")
    ap.add_argument("cmd", choices=["evaluate", "heldout", "gate", "readme", "quick", "rules"])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dev", action="store_true", help="gate: judge the development shops, not the held-out ones")
    a = ap.parse_args(argv)
    from sep.eval import report

    if a.cmd == "rules":
        changed = rules()
        if a.check and changed:
            print("ops/prometheus/rules.yml is out of date: run python -m sep.eval.cli rules", file=sys.stderr)
            return 1
        return 0
    if a.cmd == "quick":
        res = run_all(False, days=3, names=["shop_as_found", "short_ttl", "platform"])
        s = summarize(res)
        print(json.dumps({d: {k: v[k] for k in ("availability", "hit_ratio", "wrong_per_100k", "cost_eur_per_month")}
                          for d, v in s["designs"].items()}, indent=1))
        return 0
    if a.cmd == "evaluate":
        res = run_all(False)
        s = summarize(res)
        _write("dev", s)
        _write("blackfriday", {"seed": res[0]["seed"], "step_minutes": 5, "series": res[0]["bf_series"]})
        report.charts(s)
        report.readme()
        print(json.dumps({d: [v["availability"], v["wrong_per_100k"], v["cost_eur_per_month"]]
                          for d, v in s["designs"].items()}))
        return 0
    if a.cmd == "heldout":
        if LOCK.exists():
            print(f"held-out already run: {LOCK.read_text().strip()}", file=sys.stderr)
            return 1
        s = summarize(run_all(True))
        _write("heldout", s)
        LOCK.write_text(json.dumps({"ran_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
                                    "config_sha": _config_hash(), "seeds": s["world"]["seeds"]}) + "\n")
        report.readme()
        print("held-out:", gate(s) or "gate passed")
        return 0
    if a.cmd == "gate":
        held = REPORTS / "heldout.json"
        path = held if held.exists() and not a.dev else REPORTS / "dev.json"
        fails = gate(json.loads(path.read_text()))
        print(f"{path.name}: " + ("; ".join(fails) if fails else "gate passed"))
        return 1 if fails else 0
    if a.cmd == "readme":
        changed = report.readme(check=a.check)
        if a.check and changed:
            print("README results block is out of date: run python -m sep.eval.cli readme", file=sys.stderr)
            return 1
        return 0
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
